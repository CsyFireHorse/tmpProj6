#ifndef _MC_CAM_TABLE_H_
#define _MC_CAM_TABLE_H_

#include "stdint.h"
#include "zmc_types_def.h"

typedef enum _SMC_CAMTAPPETTYPE_t {
    TAPPET_pos,  // Tappet action active when the master passes its position in positive direction.
    TAPPET_all,  // Tappet action active when master passes its position in both directions.
    TAPPET_neg,  // Tappet action active when master passes its position in negative direction.
} SMC_CAMTAPPETTYPE;

typedef enum _SMC_CAMTAPPETACTION_t {
    TAPPETACTION_on,
    TAPPETACTION_off,
    TAPPETACTION_inv,
    TAPPETACTION_time,  // Switches on after a delay for a certain time period.
} SMC_CAMTAPPETACTION;


typedef struct SMC_CAMTappet {
    uint16_t ctt; // SMC_CAMTAPPETTYPE
    uint16_t cta;// SMC_CAMTAPPETACTION
    ZMC_DWORD dwDelay;  //  In case of cta = TAPPETACTION.TAPPETACTION_time, this value determines the delay time in us.

    ZMC_DWORD dwDuration;  // In case of cta = TAPPETACTION.TAPPETACTION_time, this value determines the time in us, for which the tappet is switched to on
    ZMC_INT iGroupID;      // Group or track ID of the tappet output that is switched.
    ZMC_LREAL x;           // Master position where tappet is switched.
    ZMC_DWORD dwActive;    // 16#FFFFFFFF Internal variable
} SMC_CAMTappet;


typedef enum SMC_CAM_TYPE_t {
    mcCamTypePOLY,  // 0 Polynomial description (5th degree). Deprecated, don't use.
    mcCamTypeX,     // 1 Equidistant, one-dimensional table of slave positions
    mcCamTypeXY,    // 2 Non-equidistant, two-dimensional table of master/slave positions
    mcCamTypeXYVA,  // 3 Polynomial description consisting of master position X, slave position Y,
                    // slave velocity V and slave acceleration A
} SMC_CAM_TYPE;



// https://content.helpme-codesys.com/en/libs/SM3_Basic/Current/SM3_Basic/DataTypes/CAM/MC_CAM_REF.html
typedef struct MC_CAM_TABLE {
    ZMC_WORD wCamStructID;  // 16#DC34 By means of this variable, which always has a constant
                            // value, MC_CamTableSelect checks if the entered data structure is of
                            // type MC_CAM_REF.
    SMC_CAM_TYPE
    byType;  //  Describes the cam type, that is the way in which the cam is represented.
    ZMC_BYTE byVarType;  // Defines the type of variables that enter in the curve table. Only used
                         // for byType SMC_CAM_TYPE.X or SMC_CAM_TYPE.XY
                         // see also SMC_CAM_VAR_TYPE
    ZMC_LREAL
    xStart;          // Start position of the master defining the range of master values available
    ZMC_LREAL xEnd;  // End position of the master defining the range of master values available.
    ZMC_INT nElements;  //   Number of elements that is depending on cam type the number of slave
                        //   positions, master/slave positions or XYVA points.
    ZMC_INT nTappets;   //   Number of tappet switch actions.
    ZMC_BYTE *pce;      // Pointer to actual data element which type depends on byType:
    SMC_CAMTappet *pt;
    ZMC_DWORD dwTappetActiveBits;  //    Internal variable
    ZMC_STRING strCAMName;
    ZMC_BYTE byInterpolationQuality;  // 1 1: Linear interpolation, 3: Cubic interpolation
    ZMC_BYTE byCompatibilityMode;     //   Compatibility mode: Bit0: TRUE: Periodic execution of
                                      //   tables with master width
    ZMC_BOOL bChangedOnline;          //   Internal variable
    ZMC_BOOL xPartofLM;  //   TRUE: Generated by programming system -> maintained by managers.
} MC_CAM_TABLE;


#endif