inline AxFbActionType StringToAxFbActionType(const char* str) {
    const unsigned int hash = strhash(str);
    switch(hash) {
        case strhash("AXFB_NOP"): return AXFB_NOP;
        case strhash("AX_ATTR_SET"):     return AX_ATTR_SET;
        case strhash("AX_ATTR_GET"):     return AX_ATTR_GET;
        case strhash("AX_ATTR_SET_EX"): return AX_ATTR_SET_EX;
        case strhash("AX_ATTR_GET_EX"): return AX_ATTR_GET_EX;
        
        case strhash("FB_ATTR_SET"):     return FB_ATTR_SET;
        case strhash("FB_ATTR_GET"):     return FB_ATTR_GET;
        case strhash("FB_ATTR_SET_EX"): return FB_ATTR_SET_EX;
        case strhash("FB_ATTR_GET_EX"): return FB_ATTR_GET_EX;
        default: return AXFB_NOP;
    }
}

